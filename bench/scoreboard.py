"""The public scoreboard: every library's rank on speed, build time and memory, losses included.

Reads compete.py's JSON and writes a Markdown table per run and a summary of where Epzero wins and
loses. Two kinds of run per dataset: every library at its shipped default (*-compete.json), and the
latest round of Glass against Epzero's tuned settings (*-speed-roundN.json). A library is ranked only
against what ran in the same file, so figures from different runs are never mixed.

    python bench/scoreboard.py --results bench/results/pace --out docs/scoreboard.md
"""

import argparse
import glob
import json
import math
import os
import re

# What each dataset is measured at. GloVe uses lower targets: at M=16 most libraries stop near 0.94.
TARGETS = {"glove": (0.80, 0.90, 0.93)}
DEFAULT_TARGETS = (0.90, 0.95, 0.98)
SUFFIX = "-compete.json"
ROUND = re.compile(r"(.+)-speed-round(\d+)\.json$")


def qps_at(sweep, recall):
    """QPS at a recall, interpolated log-linearly between sweep points; None if never reached."""
    points = sorted(sweep, key=lambda s: s["recall"])
    for low, high in zip(points, points[1:]):
        if low["recall"] <= recall <= high["recall"] and high["recall"] > low["recall"]:
            t = (recall - low["recall"]) / (high["recall"] - low["recall"])
            return math.exp(math.log(low["qps"]) + t * (math.log(high["qps"]) - math.log(low["qps"])))
    return None


def fmt(value, unit=""):
    return "—" if value is None else f"{value:,.0f}{unit}"


def table(run):
    """A dataset's rows, fastest first at the middle target, and Epzero's rank on each measure."""
    libraries = run["libraries"]
    name = run["dataset"].split("-")[0]
    targets = TARGETS.get(name, DEFAULT_TARGETS)
    rows = []
    for lib, data in libraries.items():
        qps = [qps_at(data["sweep"], r) for r in targets]
        rows.append({"lib": lib, "qps": qps, "build": data.get("build_seconds"), "memory": data.get("memory_mb"),
                     "top": max(s["recall"] for s in data["sweep"])})
    middle = len(targets) // 2
    rows.sort(key=lambda r: -(r["qps"][middle] or 0))
    head = ["Library"] + [f"QPS at {r}" for r in targets] + ["Highest recall", "Build", "Memory"]
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for row in rows:
        cells = [row["lib"]] + [fmt(q) for q in row["qps"]]
        cells += [f"{row['top']:.4f}", fmt(row["build"], " s"), fmt(row["memory"], " MB")]
        lines.append("| " + " | ".join(cells) + " |")

    # Epzero counts as one library: its configuration fastest at the middle target, on every measure, so a
    # configuration that builds fast but searches slowly can't stand in for the one that wins on speed.
    others = [r for r in rows if not r["lib"].startswith("epzero")]
    mine = next(r for r in rows if r["lib"].startswith("epzero"))

    def rank(score):
        return None if score(mine) is None else 1 + sum(1 for r in others if score(r) is not None and score(r) < score(mine))

    ranks = {}
    for i, target in enumerate(targets):
        ranks[f"speed at {target}"] = rank(lambda r, i=i: -r["qps"][i] if r["qps"][i] else None)
    ranks["build"] = rank(lambda r: r["build"])
    ranks["memory"] = rank(lambda r: r["memory"])
    return lines, ranks, len(others) + 1


def runs(folder):
    """A machine's files: each dataset's all-library run, then its latest tuned round."""
    files = sorted(glob.glob(os.path.join(folder, f"*{SUFFIX}")))
    latest = {}
    for path in glob.glob(os.path.join(folder, "*-speed-round*.json")):
        match = ROUND.match(os.path.basename(path))
        if match and int(match[2]) > latest.get(match[1], (0, ""))[0]:
            latest[match[1]] = (int(match[2]), path)
    tuned = [(path, f"round {number}, Glass against Epzero's tuned settings") for number, path in latest.values()]
    return sorted([(path, "every library, shipped defaults") for path in files] + tuned)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--results", default="bench/results/pace")
    parser.add_argument("--out", default="docs/scoreboard.md")
    args = parser.parse_args()
    out = ["# Scoreboard", "",
           "Generated by `bench/scoreboard.py` from each machine's raw results. Each table is one run, and a",
           "library is ranked only against the others in it. Two kinds of run: every library at its shipped",
           "default, and the latest round of Glass against Epzero's tuned settings for that dataset. Those",
           "settings were chosen on the same queries they are measured on, so treat them as development",
           "figures until a run on held-out queries. Memory is the growth in the process's resident memory",
           "while an index loads or builds, which is approximate; blank where a run didn't record it. Build",
           "time uses every core of the node. Rank 1 is best; Epzero counts as one library, ranked on every",
           "measure by its configuration fastest at the middle recall target.", ""]
    summary = []
    for machine in sorted(os.listdir(args.results)):
        files = runs(os.path.join(args.results, machine))
        if not files:
            continue
        out += [f"## {machine}", ""]
        for path, kind in files:
            with open(path, encoding="utf-8") as f:
                run = json.load(f)
            lines, ranks, count = table(run)
            cpu = run.get("environment", {}).get("cpu")
            out += [f"### {run['dataset']}: {kind}", "", f"{run['n']:,} vectors, {run['dim']} dimensions, k = {run['k']}, "
                    f"M = {run['M']}, efConstruction = {run['ef_construction']}, {run['rounds']} rounds, one search thread"
                    + (f", {cpu}." if cpu else "."), ""]
            out += lines + [""]
            summary.append((machine, f"{run['dataset']} ({kind.split(',')[0]})", ranks, count))
    if summary:
        out += ["## Where Epzero stands", "", "| Machine | Dataset | Measure | Epzero's rank |", "|---|---|---|---|"]
        for machine, dataset, ranks, count in summary:
            for measure, value in ranks.items():
                out.append(f"| {machine} | {dataset} | {measure} | {'—' if value is None else f'{value} of {count}'} |")
        out.append("")
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
